// An HTTP front for the gate and the handler, as hooks.server.ts and routes/mcp do it.
const shim: Server = createServer(async (req, res) => {
	const chunks: Buffer[] = [];
	for await (const c of req) chunks.push(c as Buffer);
	const url = new URL(req.url ?? '/', BASE);
	const headers = new Headers();
	for (const [k, v] of Object.entries(req.headers)) if (typeof v === 'string') headers.set(k, v);
	const method = req.method ?? 'GET';
	const request = new Request(url, { method, headers, body: method === 'GET' || method === 'HEAD' ? undefined : Buffer.concat(chunks) });
	let response: Response;
	if (url.pathname !== '/mcp') response = new Response('Not found', { status: 404 });
	else {
		const gate = mcpGate({ method, url, headers, ip: headers.get('x-test-ip') ?? '127.0.0.1' });
		response = gate.ok ? await handleMcp(request, gate.ctx) : gate.response;
	}
	res.writeHead(response.status, Object.fromEntries(response.headers));
	res.end(Buffer.from(await response.arrayBuffer()));
});
await new Promise<void>((r) => shim.listen(PORTS.mcp, '127.0.0.1', r));

