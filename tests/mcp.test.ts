	assert.deepEqual(await names(c), READ_TOOLS, 'control tools vanish');
	const r = await call(c, 'set_temperature', { printer: 'Prusa MK4', heater: 'bed', target: 50 });
	assert.equal(r.isError, true);
	assert.match(r.content[0].text!, /can only watch/);
	store.updateUser(op2.id, { printerAccess: 'selected' });
	store.setGrants(op2.id, [voron.id]);
	assert.deepEqual((await call(c, 'list_printers')).structuredContent.printers.map((p: { name: string }) => p.name), ['Prusa Voron'], 'a lost grant hides the printer');
	store.updateUser(op2.id, { disabled: true });
	const res = await rpc(init('2025-06-18'), { token });
	assert.equal(res.status, 403);
	assert.match(res.data.error.message, /disabled or was removed/);
	store.updateUser(op2.id, { disabled: false });
	assert.equal((await rpc(init('2025-06-18'), { token })).status, 200);
	store.deleteUser(op2.id);
	assert.equal((await rpc(init('2025-06-18'), { token })).status, 403);
