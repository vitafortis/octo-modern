test('initialize: negotiates the protocol version (2025-06-18, the latest, an unknown one)', async () => {
	const { token } = mcpToken('raw', admin, 'read');
	for (const v of ['2025-06-18', '2025-03-26', LATEST_PROTOCOL_VERSION]) {
		const r = await rpc(init(v), { token });
		assert.equal(r.status, 200, r.text);
		assert.equal(r.data.result.protocolVersion, v);
		assert.equal(r.data.result.serverInfo.name, 'octo-modern');
		assert.ok(r.data.result.capabilities.tools);
		assert.match(r.data.result.instructions, /confirm: true/);
		assert.equal(r.headers.get('mcp-session-id'), null, 'stateless: no session');
	}
	const r = await rpc(init('2099-01-01'), { token });
	assert.equal(r.data.result.protocolVersion, LATEST_PROTOCOL_VERSION, 'an unknown version gets the latest');
	// Later requests: the version header must be one we speak.
	const bad = await rpc({ jsonrpc: '2.0', id: 2, method: 'tools/list' }, { token, headers: { 'mcp-protocol-version': '1999-01-01' } });
	assert.equal(bad.status, 400);
	const good = await rpc({ jsonrpc: '2.0', id: 2, method: 'tools/list' }, { token, headers: { 'mcp-protocol-version': '2025-06-18' } });
	assert.equal(good.status, 200);
	assert.ok(good.data.result.tools.length);
	// Notifications get 202, ping answers.
	assert.equal((await rpc({ jsonrpc: '2.0', method: 'notifications/initialized' }, { token })).status, 202);
	assert.deepEqual((await rpc({ jsonrpc: '2.0', id: 3, method: 'ping' }, { token })).data.result, {});
	// An unknown tool is a protocol error; an unknown method too.
	const unknown = await rpc({ jsonrpc: '2.0', id: 4, method: 'tools/call', params: { name: 'format_disk', arguments: {} } }, { token });
	assert.equal(unknown.data.error.code, -32602);
	assert.equal((await rpc({ jsonrpc: '2.0', id: 5, method: 'resources/list' }, { token })).data.error.code, -32601);
});

