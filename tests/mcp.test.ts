test('auth: Bearer MCP tokens only; bad ones 401, throttled after 20', async () => {
	const { token } = mcpToken('auth', admin, 'read');
	const status = tokens.createToken({ name: 'dash', expiresAt: null, includeAddresses: false }, admin).token;
	const ip = { 'x-test-ip': '10.9.9.1' };
	let r = await rpc(init('2025-06-18'), { headers: ip });
	assert.equal(r.status, 401);
	assert.equal(r.headers.get('www-authenticate'), 'Bearer');
	assert.match(r.data.error.message, /MCP token required/);
	assert.equal((await rpc(init('2025-06-18'), { token: status, headers: ip })).status, 401, 'a status token opens nothing here');
	assert.equal((await rpc(init('2025-06-18'), { token: `${token}x`, headers: ip })).status, 401);
	// No query-string tokens and no cookies.
	assert.equal((await rpc(init('2025-06-18'), { path: `/mcp?token=${token}`, headers: ip })).status, 401);
	assert.equal((await rpc(init('2025-06-18'), { headers: { ...ip, cookie: `ocm_session=${token}` } })).status, 401);
	// Revoked and expired tokens.
	const revoked = mcpToken('revoked', admin, 'read');
	tokens.revokeToken(revoked.record.id);
	assert.equal((await rpc(init('2025-06-18'), { token: revoked.token, headers: ip })).status, 401);
	const expired = mcpToken('expired', admin, 'read', 'all', new Date(Date.now() - 1000).toISOString());
	assert.equal((await rpc(init('2025-06-18'), { token: expired.token, headers: ip })).status, 401);
	// The good token works from that address… until 20 failures in 5 minutes.
	assert.equal((await rpc(init('2025-06-18'), { token, headers: ip })).status, 200);
	for (let i = 0; i < 20; i++) await rpc(init('2025-06-18'), { token: 'ocx_' + 'A'.repeat(43), headers: ip });
	assert.equal((await rpc(init('2025-06-18'), { token, headers: ip })).status, 429);
	assert.equal((await rpc(init('2025-06-18'), { token, headers: { 'x-test-ip': '10.9.9.2' } })).status, 200, 'other addresses are not affected');
});

