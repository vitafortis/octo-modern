async function connect(token: string) {
	const c = new Client({ name: 'octo-modern-test', version: '1.0.0' });
	await c.connect(new StreamableHTTPClientTransport(new URL(`${BASE}/mcp`), { requestInit: { headers: { authorization: `Bearer ${token}` } } }));
	clients.push(c);
	return c;
}

/** A raw JSON-RPC POST. */
async function rpc(body: unknown, o: { token?: string; headers?: Record<string, string>; method?: string; path?: string } = {}) {
	const res = await fetch(`${BASE}${o.path ?? '/mcp'}`, {
		method: o.method ?? 'POST',
		headers: { 'content-type': 'application/json', accept: 'application/json, text/event-stream', ...(o.token ? { authorization: `Bearer ${o.token}` } : {}), ...o.headers },
		body: (o.method ?? 'POST') === 'POST' ? JSON.stringify(body) : undefined
	});
	const text = await res.text();
	let data: any = null;
	try {
		data = JSON.parse(text);
	} catch {}
	return { status: res.status, headers: res.headers, data, text };
}
const init = (protocolVersion: string) => ({ jsonrpc: '2.0', id: 1, method: 'initialize', params: { protocolVersion, capabilities: {}, clientInfo: { name: 'raw', version: '1' } } });

type Result = { content: { type: string; text?: string; data?: string; mimeType?: string }[]; structuredContent?: any; isError?: boolean };
