// --- the OctoPrint runner, unit -------------------------------------------------------------

function fakeFeed() {
	const listeners = new Set<(e: any) => void>();
	return {
		live: true,
		state: 'operational' as any,
		emit(e: any) {
			for (const l of listeners) l(e);
		},
		feed: {
			subscribe: (fn: any) => (listeners.add(fn), () => listeners.delete(fn)),
			live: () => true,
			state: () => 'operational' as any
		},
		get count() {
			return listeners.size;
		}
	};
}

test('octoprintRunner: waits for the marker, fails on firmware errors, times out, cancels with M108', async () => {
	const f = fakeFeed();
	const sent: string[][] = [];
	const run = octoprintRunner({ send: async (c) => void sent.push(c), feed: f.feed, token: () => 'tok1' });
	const ac = new AbortController();
	let done = false;
	const p = run(['G28', 'G29'], { signal: ac.signal, timeoutMs: 5_000 }).then(() => (done = true));
	await until(() => sent.length, 'sent');
	assert.deepEqual(sent[0], ['G28', 'G29', 'M400', 'M118 E1 octo-modern tok1 done']);
	f.emit({ type: 'log', lines: ['Send: G28', 'Recv: ok', 'Send: G29', 'Recv: echo:busy: processing'] });
	await sleep(30);
	assert.equal(done, false, 'still running');
	f.emit({ type: 'log', lines: ['Recv: ok', 'Send: M400', 'Recv: ok', 'Send: N12 M118 E1 octo-modern tok1 done*99'] });
	await p;
	assert.equal(f.count, 0, 'unsubscribed');

	const err = run(['G29'], { signal: new AbortController().signal, timeoutMs: 5_000 });
	await sleep(20);
	f.emit({ type: 'log', lines: ['Send: G29', 'Recv: Error:Probing Failed'] });
	await assert.rejects(err, (e: InstanceType<typeof PrepError>) => e.code === 'FAILED' && /Probing Failed/.test(e.message));

	await assert.rejects(run(['G29'], { signal: new AbortController().signal, timeoutMs: 60 }), (e: InstanceType<typeof PrepError>) => e.code === 'TIMEOUT');

	const ac2 = new AbortController();
	sent.length = 0;
	const c = run(['M190 S60'], { signal: ac2.signal, timeoutMs: 5_000 });
	await until(() => sent.length, 'sent');
	ac2.abort();
	await assert.rejects(c, (e: InstanceType<typeof PrepError>) => e.code === 'CANCELLED');
	await until(() => sent.some((s) => s[0] === 'M108'), 'M108');

	const gone = run(['G29'], { signal: new AbortController().signal, timeoutMs: 5_000 });
	await sleep(20);
	f.emit({ type: 'update', snapshot: { state: 'error', printerError: 'Thermal runaway' } });
	await assert.rejects(gone, /Thermal runaway/);

	assert.ok(isFirmwareError('Recv: Error:Probing failed'));
	assert.ok(isFirmwareError('Recv: !! Move out of range'));
	assert.ok(!isFirmwareError('Recv: Error:checksum mismatch, Last Line: 12'));
	assert.ok(!isFirmwareError('Send: M117 Error: nothing'));
});

