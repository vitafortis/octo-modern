	function finish(status) {
		const ps = s.status.print_stats;
		const map = { completed: 'complete', cancelled: 'cancelled', error: 'error' };
		ps.state = map[status];
		s.status.virtual_sdcard.is_active = false;
		s.status.pause_resume.is_paused = false;
		s.history.unshift({ job_id: String(s.history.length + 1).padStart(6, '0'), filename: ps.filename, status, start_time: s.started, end_time: now(), print_duration: ps.print_duration, total_duration: ps.total_duration, filament_used: ps.filament_used, metadata: files.get(ps.filename)?.meta ?? {}, exists: true });
		s.status.extruder.target = 0;
		s.status.heater_bed.target = 0;
	}

	function rpcError(code, message) {
		return Object.assign(new Error(message), { rpcCode: code });
	}

	function ready() {
		if (s.klippy !== 'ready') throw rpcError(503, `Klippy Host not connected`);
	}

	function startPrint(filename) {
		ready();
		if (!files.has(filename)) throw rpcError(400, `File ${filename} does not exist`);
		const ps = s.status.print_stats;
		if (ps.state === 'printing' || ps.state === 'paused') throw rpcError(400, 'Print is already in progress');
		Object.assign(ps, { state: 'printing', filename, print_duration: 0, total_duration: 0, filament_used: 0 });
		s.started = now();
		s.pausedFor = 0;
		s.status.virtual_sdcard.is_active = true;
		s.status.virtual_sdcard.file_path = `/home/pi/printer_data/gcodes/${filename}`;
		s.status.extruder.target = 215;
		s.status.heater_bed.target = 60;
		gcode.push(`SDCARD_PRINT_FILE FILENAME="${filename}"`);
		return 'ok';
	}

