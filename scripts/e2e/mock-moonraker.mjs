// A Moonraker stand-in (Klipper's API server) for the node tests and `pnpm e2e:klipper`:
// HTTP API plus the JSON-RPC websocket on /websocket, with a simulated printer (heaters that
// approach their targets, prints that progress over `printSeconds`, pause/resume/cancel,
// emergency stop and firmware restart), files with slicer metadata and thumbnails, webcams,
// job history and Mainsail temperature presets. No dependencies; never contacts anything.
//
//   const mr = await startMockMoonraker({ port: 5510 });
//   mr.url, mr.calls (every HTTP request and RPC call), mr.gcode (every G-code script), mr.state
