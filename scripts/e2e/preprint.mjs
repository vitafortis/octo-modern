// End-to-end test of "Before each print" (bed leveling and pre-print G-code), against local
// mocks only: a mock OctoPrint (push socket, a serial queue that takes its time over G29 and
// M190), a mock Moonraker (blocking gcode.script) and a webhook catcher. No real printer.
//
//   pnpm e2e:preprint                   # build, run, test, screenshot, clean up
//   E2E_KEEP=1 pnpm e2e:preprint        # leave the app and mocks running afterwards
//   E2E_SKIP_BUILD=1 pnpm e2e:preprint  # reuse ./build
//
// Ports 5600–5603 (E2E_PORT_BASE moves them): app +0, OctoPrint +1, Moonraker +2, webhook +3.
// Needs a Playwright Chromium. Screenshots land in docs/screenshots/.
import { execFileSync, spawn } from 'node:child_process';
import { createServer } from 'node:http';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { startMockOctoPrint } from './mock-octoprint.mjs';
import { startMockMoonraker } from './mock-moonraker.mjs';

const ROOT = resolve(import.meta.dirname, '../..');
const SHOTS = join(ROOT, 'docs/screenshots');
const PORT_BASE = Number(process.env.E2E_PORT_BASE ?? 5600);
const APP_PORT = PORT_BASE;
const APP = `http://127.0.0.1:${APP_PORT}`;
const ADMIN = { email: 'admin@example.com', name: 'Ada Admin', password: 'e2e-admin-password' };
const OPERATOR = { email: 'operator@example.com', name: 'Otto Operator', password: 'e2e-operator-password' };
const VIEWER = { email: 'viewer@example.com', name: 'Vera Viewer', password: 'e2e-viewer-password' };
const OP_KEY = 'mk4-preprint-key';

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const log = (...a) => console.log('•', ...a);

let app;
let browser;
const closers = [];
const hooks = [];
const dataDir = mkdtempSync(join(tmpdir(), 'ocm-e2e-preprint-'));

async function waitFor(fn, label, { tries = 120, every = 250 } = {}) {
	let last;
	for (let i = 0; i < tries; i++) {
		try {
			const v = await fn();
			if (v) return v;
		} catch (err) {
			last = err;
		}
		await sleep(every);
	}
	throw new Error(`Timed out waiting for ${label}${last ? `: ${last.message}` : ''}`);
}

function client() {
	let cookie = '';
	const call = async (method, path, body) => {
		const res = await fetch(`${APP}${path}`, {
			method,
			redirect: 'manual',
			headers: { ...(body !== undefined ? { 'content-type': 'application/json' } : {}), ...(cookie ? { cookie } : {}), origin: APP },
			body: body === undefined ? undefined : JSON.stringify(body)
		});
		const set = res.headers.get('set-cookie');
		if (set) cookie = set.split(';')[0];
		const text = await res.text();
		let data = null;
		try {
			data = JSON.parse(text);
		} catch {}
		return { status: res.status, data, text };
	};
	return { get: (p) => call('GET', p), post: (p, b) => call('POST', p, b ?? {}), put: (p, b) => call('PUT', p, b), del: (p) => call('DELETE', p, {}) };
}

// Demo files: a Cura file that only loads a saved mesh, and a PrusaSlicer file that levels itself.
const CURA = `;FLAVOR:Marlin\n;Generated with Cura_SteamEngine 5.7.1\nM140 S60\nM190 S60\nM104 S205\nM109 S205\nG28 ;Home\nM420 S1 ;Load the saved mesh\nG92 E0\nG1 X0.1 Y20 Z0.3 F5000.0\nG1 X0.1 Y200.0 Z0.3 F1500.0 E15\n;LAYER_COUNT:120\n;LAYER:0\nG1 X10 Y10 E1\n`;
const PRUSA = `; generated by PrusaSlicer 2.8.1\nM107\n;TYPE:Custom\nM140 S60\nM190 S60\nM109 S215\nG28 W\nG80 ; mesh bed leveling\nG92 E0\n;LAYER_CHANGE\n;Z:0.2\nG1 Z.2\n`;
const KLIPPER = `; generated by OrcaSlicer 2.1.1\n;TYPE:Custom\nM190 S65\nG28\nBED_MESH_PROFILE LOAD=default\n;LAYER_CHANGE\nG1 Z.2\n`;

async function main() {
	mkdirSync(SHOTS, { recursive: true });
	log('starting a mock OctoPrint, a mock Moonraker and a webhook catcher');
	const mk4Op = await startMockOctoPrint({ port: PORT_BASE + 1, apiKey: OP_KEY, push: true, connectMs: 300, printSeconds: 600, levelMs: 3000, homeMs: 400, files: { 'calibration_cube.gcode': CURA, 'benchy_0.2mm_PLA.gcode': PRUSA } });
	const voron = await startMockMoonraker({ port: PORT_BASE + 2, tickMs: 100, printSeconds: 600, levelMs: 2500 });
	voron.addFile('phone_stand_PETG.gcode', KLIPPER);
	const hookServer = createServer((req, res) => {
		let body = '';
		req.on('data', (d) => (body += d));
		req.on('end', () => {
			hooks.push(JSON.parse(body));
			res.end('ok');
		});
	});
	await new Promise((r) => hookServer.listen(PORT_BASE + 3, '127.0.0.1', r));
	closers.push(mk4Op.close, voron.close, () => (hookServer.closeAllConnections(), new Promise((r) => hookServer.close(r))));
	await fetch(`${mk4Op.url}/api/connection`, { method: 'POST', headers: { 'x-api-key': OP_KEY, 'content-type': 'application/json' }, body: JSON.stringify({ command: 'connect' }) });

	if (!process.env.E2E_SKIP_BUILD) {
		log('building');
		execFileSync('pnpm', ['build'], { cwd: ROOT, stdio: 'ignore' });
	}
	log(`starting octo·modern on ${APP}`);
	app = spawn('node', ['build'], {
		cwd: ROOT,
		stdio: ['ignore', 'pipe', 'pipe'],
		env: {
			...process.env,
			PORT: String(APP_PORT),
			HOST: '127.0.0.1',
			OCM_DATA_DIR: dataDir,
			OCM_POLL_INTERVAL_MS: '2000',
			OCM_ADMIN_EMAIL: ADMIN.email,
			OCM_ADMIN_PASSWORD: ADMIN.password,
			OCM_ADMIN_NAME: ADMIN.name,
			NODE_OPTIONS: '--disable-warning=ExperimentalWarning'
		}
	});
	let appLog = '';
	app.stdout.on('data', (d) => (appLog += d));
	app.stderr.on('data', (d) => (appLog += d));
	app.on('exit', (code, signal) => (appLog += `\n[app exited: ${code ?? signal}]\n`));
	process.on('exit', () => {
		try {
			writeFileSync(join(dataDir, 'app.log'), appLog);
		} catch {}
	});
	await waitFor(async () => (await fetch(`${APP}/api/health`)).ok, 'the app');

	const admin = client();
	assert.equal((await admin.post('/api/auth/login', ADMIN)).status, 200);
	const mk4 = (await admin.post('/api/printers', { name: 'Prusa MK4', baseUrl: mk4Op.url, apiKey: OP_KEY, color: 'violet' })).data;
	const vor = (await admin.post('/api/printers', { name: 'Voron 2.4', kind: 'moonraker', baseUrl: voron.url, color: 'cyan' })).data;
	for (const u of [
		{ ...OPERATOR, role: 'operator' },
		{ ...VIEWER, role: 'viewer' }
	]) assert.equal((await admin.post('/api/users', u)).status, 201);
	const operator = client();
	const viewer = client();
	assert.equal((await operator.post('/api/auth/login', OPERATOR)).status, 200);
	assert.equal((await viewer.post('/api/auth/login', VIEWER)).status, 200);
	const snap = async (id) => (await admin.get('/api/printers/status')).data.find((s) => s.id === id);
	const stateOf = async (id) => (await snap(id))?.state;
	const audits = async (action) => (await admin.get(`/api/audit?action=${action}`)).data;
	const cancelPrint = async (id) => {
		assert.equal((await operator.post(`/api/printers/${id}/job`, { command: 'cancel', confirm: true })).status, 200);
		await waitFor(async () => (await stateOf(id)) === 'operational', 'idle again');
	};
	await waitFor(async () => (await stateOf(mk4.id)) === 'operational' && (await stateOf(vor.id)) === 'operational', 'both printers ready');

	// --- off by default --------------------------------------------------------------------------
	log('off by default: a start goes straight through, nothing is sent first');
	let r = await operator.post(`/api/printers/${mk4.id}/files/select`, { origin: 'local', path: 'calibration_cube.gcode', print: true });
	assert.equal(r.status, 200, r.text);
	assert.equal(r.data.preparing, false);
	await waitFor(async () => (await stateOf(mk4.id)) === 'printing', 'printing');
	assert.deepEqual(mk4Op.state.executed, []);
	await cancelPrint(mk4.id);

	// --- roles ---------------------------------------------------------------------------------------
	log('roles: settings are admin-only');
	assert.equal((await viewer.get('/api/settings/preprint')).status, 403);
	assert.equal((await operator.put('/api/settings/preprint', { leveling: { enabled: true } })).status, 403);
	assert.equal((await operator.get(`/api/printers/${mk4.id}/preprint/settings`)).status, 403);
	assert.equal((await operator.put(`/api/printers/${mk4.id}/preprint/settings`, { leveling: { mode: 'none' } })).status, 403);
	assert.equal((await viewer.get(`/api/printers/${mk4.id}/preprint?path=calibration_cube.gcode`)).status, 403, 'plans are for operators');
	assert.equal((await viewer.get(`/api/printers/${mk4.id}/preprint`)).status, 200);
	r = await admin.put('/api/settings/preprint', { snippet: { enabled: true, skipPattern: '/(oops/' } });
	assert.equal(r.status, 400);
	assert.match(r.data.message, /Not a valid regular expression/);

	log('global defaults: level (heat first), then a snippet');
	r = await admin.put('/api/settings/preprint', {
		leveling: { enabled: true, heatBed: true, bedTemp: 60 },
		snippet: { enabled: true, gcode: 'M117 Printing from octo·modern\nG92 E0', match: 'exact' },
		timeoutMin: 20
	});
	assert.equal(r.status, 200, r.text);
	assert.equal(r.data.leveling.octoprintCommand, 'G28\nG29');
	assert.ok((await audits('settings.preprint')).some((e) => /leveling on/.test(e.detail)));

	// --- the plan and the start ------------------------------------------------------------------------
	log('OctoPrint: the start asks with the plan first');
	mk4Op.state.executed.length = 0;
	r = await operator.post(`/api/printers/${mk4.id}/files/select`, { origin: 'local', path: 'calibration_cube.gcode', print: true });
	assert.equal(r.status, 409);
	assert.equal(r.data.confirmRequired, true);
	assert.deepEqual(r.data.preprint.steps.map((s) => [s.kind, s.run]), [['heat', true], ['level', true], ['snippet', true]]);
	assert.deepEqual(r.data.preprint.steps[0].commands, ['M190 S60']);
	r = await operator.get(`/api/printers/${mk4.id}/preprint?path=benchy_0.2mm_PLA.gcode`);
	assert.deepEqual(
		r.data.plan.steps.map((s) => [s.kind, s.run]),
		[['level', false], ['snippet', true]],
		'the PrusaSlicer file levels itself (G80)'
	);
	assert.match(r.data.plan.steps[0].reason, /G80/);

	log('OctoPrint: run it: Preparing, the steps in order, then the file');
	r = await operator.post(`/api/printers/${mk4.id}/files/select`, { origin: 'local', path: 'calibration_cube.gcode', print: true, preprint: 'run' });
	assert.equal(r.status, 200, r.text);
	assert.equal(r.data.preparing, true);
	const prepping = await waitFor(async () => (await snap(mk4.id))?.preparing, 'Preparing on the status');
	assert.equal(prepping.file, 'calibration_cube.gcode');
	assert.equal(prepping.by, OPERATOR.name);
	assert.equal((await viewer.del(`/api/printers/${mk4.id}/preprint`)).status, 403);
	r = await operator.post(`/api/printers/${mk4.id}/files/select`, { origin: 'local', path: 'calibration_cube.gcode', print: true, preprint: 'run' });
	assert.equal(r.status, 409, 'one preparation at a time');
	assert.equal((await stateOf(mk4.id)), 'operational');
	await waitFor(async () => (await stateOf(mk4.id)) === 'printing', 'printing after the steps', { tries: 120 });
	assert.deepEqual(
		mk4Op.state.executed.filter((l) => !/^M118/.test(l)),
		['M190 S60', 'M400', 'G28', 'G29', 'M400', 'M117 Printing from octo·modern', 'G92 E0', 'M400']
	);
	assert.equal((await snap(mk4.id)).preparing, null);
	assert.ok((await audits('preprint.done')).length === 1);
	assert.ok((await audits('job.start')).some((e) => e.userEmail === OPERATOR.email && /calibration_cube/.test(e.detail)));
	await cancelPrint(mk4.id);

	log('OctoPrint: "skip this time" starts the file as it is');
	mk4Op.state.executed.length = 0;
	r = await operator.post(`/api/printers/${mk4.id}/files/select`, { origin: 'local', path: 'calibration_cube.gcode', print: true, preprint: 'skip' });
	assert.equal(r.data.preparing, false);
	await waitFor(async () => (await stateOf(mk4.id)) === 'printing', 'printing');
	assert.deepEqual(mk4Op.state.executed, []);
	assert.ok((await audits('preprint.skip')).some((e) => /skipped by request/.test(e.detail)));
	await cancelPrint(mk4.id);

	log('OctoPrint: probing fails → not started, print.prestart_failed webhook');
	const hookChannel = await admin.post('/api/settings/notifications/channels', { type: 'webhook', name: 'e2e hook', secrets: { url: `http://127.0.0.1:${PORT_BASE + 3}/prep` } });
	assert.equal(hookChannel.status, 201, hookChannel.text);
	assert.equal((await admin.put('/api/settings/notifications', { rules: [{ name: 'Prep', printers: 'all', events: ['print.prestart_failed'], channels: [hookChannel.data.channel.id] }] })).status, 200);
	mk4Op.state.failOn = /^G29/;
	r = await operator.post(`/api/printers/${mk4.id}/files/select`, { origin: 'local', path: 'calibration_cube.gcode', print: true, preprint: 'run' });
	assert.equal(r.data.preparing, true);
	const hook = await waitFor(() => hooks.find((h) => h.event === 'print.prestart_failed'), 'the webhook');
	assert.match(hook.title, /Print not started: Prusa MK4/);
	assert.match(hook.message, /Bed leveling failed: The printer reported: Error:Probing failed/);
	await sleep(500);
	assert.equal(await stateOf(mk4.id), 'operational');
	assert.ok((await audits('preprint.fail')).length === 1);

	// --- per printer -------------------------------------------------------------------------------------
	log('per printer: Voron gets its own leveling, no snippet');
	r = await admin.put(`/api/printers/${vor.id}/preprint/settings`, { leveling: { mode: 'custom', command: 'G28\nQUAD_GANTRY_LEVEL\nBED_MESH_CALIBRATE', heatBed: false }, snippet: { mode: 'none' } });
	assert.equal(r.status, 200, r.text);
	r = await operator.post(`/api/printers/${vor.id}/files/select`, { origin: 'local', path: 'phone_stand_PETG.gcode', print: true });
	assert.equal(r.status, 409);
	assert.deepEqual(r.data.preprint.steps.map((s) => [s.kind, s.run]), [['level', true]], 'BED_MESH_PROFILE LOAD isn’t leveling');
	const before = voron.gcode.length;
	r = await operator.post(`/api/printers/${vor.id}/files/select`, { origin: 'local', path: 'phone_stand_PETG.gcode', print: true, preprint: 'run' });
	assert.equal(r.data.preparing, true);
	await waitFor(async () => (await stateOf(vor.id)) === 'printing', 'Voron printing', { tries: 120 });
	assert.deepEqual(voron.gcode.slice(before), ['G28\nQUAD_GANTRY_LEVEL\nBED_MESH_CALIBRATE', 'SDCARD_PRINT_FILE FILENAME="phone_stand_PETG.gcode"']);
	await cancelPrint(vor.id);

	log('Cancel: the preparation stops and the file doesn’t start');
	r = await operator.post(`/api/printers/${vor.id}/files/select`, { origin: 'local', path: 'phone_stand_PETG.gcode', print: true, preprint: 'run' });
	await waitFor(async () => (await snap(vor.id))?.preparing?.step === 'level', 'leveling');
	assert.equal((await operator.del(`/api/printers/${vor.id}/preprint`)).status, 200);
	await waitFor(async () => !(await snap(vor.id))?.preparing, 'Preparing cleared');
	await sleep(3000);
	assert.notEqual(await stateOf(vor.id), 'printing');
	assert.ok((await audits('preprint.cancel')).some((e) => e.userEmail === OPERATOR.email));

	// --- browser ------------------------------------------------------------------------------------------
	browser = await chromium.launch();
	const newPage = async (theme, width = 1440, height = 900) => {
		const mobile = width < 640 ? { hasTouch: true, isMobile: true } : {};
		const ctx = await browser.newContext({ viewport: { width, height }, deviceScaleFactor: width < 640 ? 2 : 1, colorScheme: theme, ...mobile });
		await ctx.addInitScript((t) => localStorage.setItem('ocm-theme', t), theme);
		const page = await ctx.newPage();
		const errors = [];
		page.on('pageerror', (e) => errors.push(String(e)));
		page.on('console', (m) => m.type() === 'error' && !/Failed to load resource/.test(m.text()) && errors.push(m.text()));
		page.errors = errors;
		return page;
	};
	const signIn = async (page, who) => {
		await page.goto(`${APP}/login`);
		await page.waitForLoadState('networkidle');
		await page.fill('#email', who.email);
		await page.fill('#pw', who.password);
		await page.click('button:has-text("Sign in")');
		await page.waitForURL((u) => !u.pathname.startsWith('/login'));
	};
	const shot = async (page, name, opts = {}) => {
		await page.screenshot({ path: join(SHOTS, `${name}.png`), ...opts });
		log(`  screenshot ${name}.png`);
	};

	log('browser: Settings → Before each print (dark and light)');
	const pages = [];
	for (const theme of ['dark', 'light']) {
		const page = await newPage(theme);
		pages.push(page);
		await signIn(page, ADMIN);
		await page.goto(`${APP}/settings`);
		const card = page.getByTestId('preprint-settings');
		await card.waitFor();
		await card.locator('textarea[data-testid="prep-snippet"]').waitFor();
		assert.equal(await card.getByTestId('prep-snippet').inputValue(), 'M117 Printing from octo·modern\nG92 E0');
		await card.scrollIntoViewIfNeeded();
		await shot(card, theme === 'dark' ? 'preprint-settings' : 'preprint-settings-light');
	}

	log('browser: the printer dialog section');
	{
		const page = pages[0];
		await page.goto(`${APP}/p/${vor.id}`);
		await page.getByRole('button', { name: 'Edit server' }).click();
		const section = page.getByTestId('printer-preprint');
		await section.waitFor();
		assert.equal(await section.evaluate((d) => d.open), true, 'a customised printer opens the section');
		assert.equal(await section.getByTestId('printer-level-command').inputValue(), 'G28\nQUAD_GANTRY_LEVEL\nBED_MESH_CALIBRATE');
		await section.scrollIntoViewIfNeeded();
		await shot(page.getByRole('dialog'), 'preprint-printer');
		// Change it in the dialog: the snippet back to the default; saved with the printer.
		await section.getByRole('radio', { name: 'Use the default' }).nth(1).click();
		await page.getByRole('button', { name: 'Save changes' }).click();
		await waitFor(async () => (await admin.get(`/api/printers/${vor.id}/preprint/settings`)).data.settings.snippet.mode === 'default', 'saved from the dialog');
		assert.ok((await audits('printer.preprint')).length >= 2);
	}

	log('browser: start from Files → the plan → Preparing with Cancel (operator)');
	const op = await newPage('dark');
	pages.push(op);
	await signIn(op, OPERATOR);
	await op.goto(`${APP}/p/${mk4.id}?tab=files`);
	await op.locator('tr[data-file="calibration_cube.gcode"]').getByRole('button', { name: 'Print', exact: true }).click();
	const dialog = op.getByRole('dialog');
	await dialog.getByTestId('confirm-steps').waitFor();
	assert.equal(await dialog.getByTestId('confirm-steps').locator('li').count(), 3);
	await op.waitForTimeout(300);
	await shot(dialog, 'preprint-confirm');
	mk4Op.state.executed.length = 0;
	await dialog.getByRole('button', { name: 'Prepare and print' }).click();
	const banner = op.getByTestId(`preparing-${mk4.id}`);
	await banner.waitFor();
	await op.goto(`${APP}/p/${mk4.id}`);
	await banner.getByText(/Leveling the bed/).waitFor({ timeout: 15_000 });
	await op.waitForTimeout(400);
	await shot(op, 'preprint-preparing');
	await waitFor(async () => (await stateOf(mk4.id)) === 'printing', 'printing', { tries: 120 });
	await cancelPrint(mk4.id);

	log('browser: light theme and a phone, cancelling from the banner');
	const light = await newPage('light');
	const phone = await newPage('dark', 390, 844);
	pages.push(light, phone);
	await signIn(light, OPERATOR);
	await signIn(phone, OPERATOR);
	r = await operator.post(`/api/printers/${mk4.id}/files/select`, { origin: 'local', path: 'calibration_cube.gcode', print: true, preprint: 'run' });
	assert.equal(r.data.preparing, true);
	await light.goto(`${APP}/p/${mk4.id}`);
	await phone.goto(`${APP}/p/${mk4.id}`);
	await light.getByTestId(`preparing-${mk4.id}`).getByText(/Leveling the bed/).waitFor({ timeout: 15_000 });
	await phone.getByTestId(`preparing-${mk4.id}`).getByText(/Leveling the bed/).waitFor({ timeout: 15_000 });
	await light.waitForTimeout(300);
	await shot(light, 'preprint-preparing-light');
	await shot(phone, 'mobile-preprint');
	// The overview card shows it too.
	await light.goto(`${APP}/`);
	await light.getByTestId(`preparing-${mk4.id}`).waitFor();
	await phone.getByTestId(`preparing-${mk4.id}`).getByRole('button', { name: 'Cancel' }).click();
	await phone.getByRole('dialog').getByRole('button', { name: 'Cancel preparation' }).click();
	await phone.getByTestId(`preparing-${mk4.id}`).waitFor({ state: 'detached', timeout: 10_000 });
	await sleep(3500);
	assert.equal(await stateOf(mk4.id), 'operational', 'not started after cancelling');

	for (const p of pages) assert.deepEqual(p.errors, [], 'no browser errors');
	log('all pre-print e2e checks passed');
}

async function cleanup(ok) {
	await browser?.close().catch(() => {});
	if (process.env.E2E_KEEP) {
		log(`E2E_KEEP: app still running on ${APP} (pid ${app?.pid}), data in ${dataDir}`);
		return;
	}
	app?.kill();
	for (const c of closers) await Promise.resolve(c()).catch(() => {});
	if (ok) rmSync(dataDir, { recursive: true, force: true });
}

try {
	await main();
	await cleanup(true);
	process.exit(0);
} catch (err) {
	console.error('✗ e2e failed:', err);
	console.error(`  app log: ${join(dataDir, 'app.log')}`);
	await cleanup(false);
	process.exit(1);
}
