// End-to-end test of the built-in MCP server (/mcp), against local mocks only: two mock
// OctoPrints (one with a webcam). A token is created through Settings → Integrations in a
// real browser, then the official MCP SDK client connects to the built app over HTTP and
// uses it: tools per access level, reading status and a camera picture, a print started
// and cancelled with the confirm steps, the audit log. No real printer, no external service.
//
//   pnpm e2e:mcp                   # build, run, test, screenshot, clean up
//   E2E_KEEP=1 pnpm e2e:mcp        # leave the app and mocks running afterwards
//   E2E_SKIP_BUILD=1 pnpm e2e:mcp  # reuse ./build
//
// Ports 4700–4702 (E2E_PORT_BASE moves them): app +0, OctoPrints +1, +2.
// Needs a Playwright Chromium. Screenshots land in docs/screenshots/.
import { execFileSync, spawn } from 'node:child_process';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';
import { startMockOctoPrint } from './mock-octoprint.mjs';

const ROOT = resolve(import.meta.dirname, '../..');
const SHOTS = join(ROOT, 'docs/screenshots');
const PORT_BASE = Number(process.env.E2E_PORT_BASE ?? 4700);
const APP_PORT = PORT_BASE;
const APP = `http://127.0.0.1:${APP_PORT}`;
const ADMIN = { email: 'admin@example.com', name: 'Ada Admin', password: 'e2e-admin-password' };
const OPERATOR = { email: 'operator@example.com', name: 'Otto Operator', password: 'e2e-operator-password' };

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const log = (...a) => console.log('•', ...a);

let app;
let browser;
const closers = [];
const dataDir = mkdtempSync(join(tmpdir(), 'ocm-e2e-mcp-'));

async function waitFor(fn, label, { tries = 120, every = 250 } = {}) {
	let last;
	for (let i = 0; i < tries; i++) {
		try {
			const v = await fn();
			if (v) return v;
		} catch (err) {
			last = err;
		}
		await sleep(every);
	}
	throw new Error(`Timed out waiting for ${label}${last ? `: ${last.message}` : ''}`);
}

function client() {
	let cookie = '';
	const call = async (method, path, body) => {
		const res = await fetch(`${APP}${path}`, {
			method,
			redirect: 'manual',
			headers: { ...(body !== undefined ? { 'content-type': 'application/json' } : {}), ...(cookie ? { cookie } : {}), origin: APP },
			body: body === undefined ? undefined : JSON.stringify(body)
		});
		const set = res.headers.get('set-cookie');
		if (set) cookie = set.split(';')[0];
		const text = await res.text();
		let data = null;
		try {
			data = JSON.parse(text);
		} catch {}
		return { status: res.status, data, text };
	};
	return { get: (p) => call('GET', p), post: (p, b) => call('POST', p, b ?? {}), put: (p, b) => call('PUT', p, b), del: (p) => call('DELETE', p, {}) };
}

const mcpClients = [];
async function mcp(token, headers = {}) {
	const c = new Client({ name: 'octo-modern-e2e', version: '1.0.0' });
	await c.connect(new StreamableHTTPClientTransport(new URL(`${APP}/mcp`), { requestInit: { headers: { authorization: `Bearer ${token}`, ...headers } } }));
	mcpClients.push(c);
	return c;
}
const call = (c, name, args = {}) => c.callTool({ name, arguments: args });

const GCODE = '; generated by PrusaSlicer 2.8.1\nM140 S60\nM190 S60\nM109 S215\nG28\n;LAYER_CHANGE\nG1 Z.2\n';

async function main() {
	mkdirSync(SHOTS, { recursive: true });
	log('starting two mock OctoPrints');
	const mk4Op = await startMockOctoPrint({ port: PORT_BASE + 1, apiKey: 'mk4-mcp-key', push: true, connectMs: 300, printSeconds: 900, files: { 'benchy_0.2mm_PLA.gcode': GCODE, 'parts/cable_clip.gcode': GCODE } });
	const miniOp = await startMockOctoPrint({ port: PORT_BASE + 2, apiKey: 'mini-mcp-key', push: true, connectMs: 300, printSeconds: 900 });
	closers.push(mk4Op.close, miniOp.close);
	for (const m of [mk4Op, miniOp]) await fetch(`${m.url}/api/connection`, { method: 'POST', headers: { 'x-api-key': m.apiKey, 'content-type': 'application/json' }, body: JSON.stringify({ command: 'connect' }) });

	if (!process.env.E2E_SKIP_BUILD) {
		log('building');
		execFileSync('pnpm', ['build'], { cwd: ROOT, stdio: 'ignore' });
	}
	log(`starting octo·modern on ${APP}`);
	app = spawn('node', ['build'], {
		cwd: ROOT,
		stdio: ['ignore', 'pipe', 'pipe'],
		env: {
			...process.env,
			PORT: String(APP_PORT),
			HOST: '127.0.0.1',
			OCM_DATA_DIR: dataDir,
			OCM_POLL_INTERVAL_MS: '2000',
			OCM_ADMIN_EMAIL: ADMIN.email,
			OCM_ADMIN_PASSWORD: ADMIN.password,
			OCM_ADMIN_NAME: ADMIN.name,
			NODE_OPTIONS: '--disable-warning=ExperimentalWarning'
		}
	});
	let appLog = '';
	app.stdout.on('data', (d) => (appLog += d));
	app.stderr.on('data', (d) => (appLog += d));
	app.on('exit', (code, signal) => (appLog += `\n[app exited: ${code ?? signal}]\n`));
	process.on('exit', () => {
		try {
			writeFileSync(join(dataDir, 'app.log'), appLog);
		} catch {}
	});
	await waitFor(async () => (await fetch(`${APP}/api/health`)).ok, 'the app');

	const admin = client();
	assert.equal((await admin.post('/api/auth/login', ADMIN)).status, 200);
	const mk4 = (await admin.post('/api/printers', { name: 'Prusa MK4', baseUrl: mk4Op.url, apiKey: 'mk4-mcp-key', color: 'violet', webcamUrl: '/webcam/?action=snapshot' })).data;
	const mini = (await admin.post('/api/printers', { name: 'Prusa Mini', baseUrl: miniOp.url, apiKey: 'mini-mcp-key', color: 'cyan' })).data;
	assert.equal((await admin.post('/api/users', { ...OPERATOR, role: 'operator' })).status, 201);
	const stateOf = async (id) => (await admin.get('/api/printers/status')).data.find((s) => s.id === id)?.state;
	await waitFor(async () => (await stateOf(mk4.id)) === 'operational' && (await stateOf(mini.id)) === 'operational', 'both printers ready');
	// The queue is paused so confirming the bed doesn't dispatch anything.
	await admin.post('/api/queue/pause', { paused: true });

	// --- a token through the UI ------------------------------------------------------------------
	browser = await chromium.launch();
	const pages = [];
	const newPage = async (theme, width = 1440, height = 1000) => {
		const mobile = width < 640 ? { hasTouch: true, isMobile: true } : {};
		const ctx = await browser.newContext({ viewport: { width, height }, deviceScaleFactor: width < 640 ? 2 : 1, colorScheme: theme, ...mobile });
		await ctx.addInitScript((t) => localStorage.setItem('ocm-theme', t), theme);
		await ctx.grantPermissions(['clipboard-read', 'clipboard-write'], { origin: APP });
		const page = await ctx.newPage();
		const errors = [];
		page.on('pageerror', (e) => errors.push(String(e)));
		page.on('console', (m) => m.type() === 'error' && !/Failed to load resource/.test(m.text()) && errors.push(m.text()));
		page.errors = errors;
		pages.push(page);
		return page;
	};
	const signIn = async (page, who) => {
		await page.goto(`${APP}/login`);
		await page.waitForLoadState('networkidle');
		await page.fill('#email', who.email);
		await page.fill('#pw', who.password);
		await page.click('button:has-text("Sign in")');
		await page.waitForURL((u) => !u.pathname.startsWith('/login'));
	};
	const shot = async (page, name, opts = {}) => {
		await page.screenshot({ path: join(SHOTS, `${name}.png`), ...opts });
		log(`  screenshot ${name}.png`);
	};
	const dialog = (page) => page.locator('dialog[open]');

	let token = null;
	for (const theme of ['dark', 'light']) {
		log(`browser (${theme}): Settings → Integrations → New MCP token`);
		const page = await newPage(theme);
		await signIn(page, ADMIN);
		await page.goto(`${APP}/integrations#mcp`);
		await page.waitForLoadState('networkidle');
		await page.getByTestId('mcp-new').click();
		await page.fill('#mcp-name', theme === 'dark' ? 'Claude Code on the workshop Mac' : 'Claude Desktop');
		await dialog(page).getByRole('radio', { name: /Control/ }).click();
		await dialog(page).getByRole('tab', { name: 'Chosen printers' }).click();
		await dialog(page).getByTestId('mcp-printers').getByText('Prusa MK4').click();
		await sleep(300);
		await shot(dialog(page), theme === 'dark' ? 'mcp-token-dialog' : 'mcp-token-dialog-light');
		await dialog(page).getByRole('button', { name: 'Create token' }).click();
		await dialog(page).getByTestId('mcp-created').waitFor();
		const t = (await dialog(page).locator('code').first().textContent()).trim();
		assert.match(t, /^ocx_[A-Za-z0-9_-]{43}$/);
		const snippet = await dialog(page).getByTestId('mcp-snippet').textContent();
		assert.ok(snippet.includes(`claude mcp add --transport http octo-modern ${APP}/mcp --header "Authorization: Bearer ${t}"`), snippet);
		await sleep(300);
		await shot(dialog(page), theme === 'dark' ? 'mcp-token-setup' : 'mcp-token-setup-light');
		await dialog(page).getByRole('tab', { name: 'Claude Desktop' }).click();
		const desktop = JSON.parse(await dialog(page).getByTestId('mcp-snippet').textContent());
		assert.deepEqual(desktop.mcpServers['octo-modern'].args.slice(0, 4), ['-y', 'mcp-remote', `${APP}/mcp`, '--header']);
		assert.equal(desktop.mcpServers['octo-modern'].env.AUTH_HEADER, `Bearer ${t}`);
		await dialog(page).getByRole('button', { name: 'Done' }).click();
		await page.locator('[data-testid="mcp-tokens"] tbody tr').first().waitFor();
		if (theme === 'dark') {
			token = t;
			await shot(page.locator('#mcp'), 'mcp-integrations');
		}
	}

	log('browser (phone): the dialog as a sheet');
	const phone = await newPage('dark', 390, 844);
	await signIn(phone, ADMIN);
	await phone.goto(`${APP}/integrations#mcp`);
	await phone.waitForLoadState('networkidle');
	await phone.getByTestId('mcp-new').click();
	await phone.fill('#mcp-name', 'Phone test');
	await sleep(400);
	await shot(phone, 'mcp-token-phone');
	const overflow = await phone.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);
	assert.ok(overflow <= 0, `no sideways scrolling on a phone (${overflow}px)`);

	// --- the MCP client ------------------------------------------------------------------------------
	log('MCP client: initialize and list tools (control token for the MK4)');
	const c = await mcp(token);
	assert.equal(c.getServerVersion().name, 'octo-modern');
	const tools = (await c.listTools()).tools.map((t) => t.name);
	for (const n of ['list_printers', 'get_printer_status', 'get_camera_snapshot', 'start_print', 'cancel_print', 'confirm_bed_clear', 'set_temperature']) assert.ok(tools.includes(n), n);

	let r = await call(c, 'list_printers');
	assert.deepEqual(r.structuredContent.printers.map((p) => p.name), ['Prusa MK4'], 'only the chosen printer');
	r = await call(c, 'get_camera_snapshot', { printer: 'prusa mk4' });
	assert.equal(r.content[0].type, 'image');
	assert.equal(r.content[0].mimeType, 'image/jpeg');
	r = await call(c, 'get_printer_status', { printer: 'Prusa Mini' });
	assert.equal(r.isError, true, 'the other printer is out of scope');

	log('MCP client: start a print (bed check, describe, confirm), then cancel it');
	r = await call(c, 'start_print', { printer: 'Prusa MK4', file: 'benchy', confirm: true });
	assert.equal(r.structuredContent.needs, 'bed_clear');
	r = await call(c, 'confirm_bed_clear', { printer: 'Prusa MK4' });
	assert.equal(r.structuredContent.done, true);
	r = await call(c, 'start_print', { printer: 'Prusa MK4', file: 'benchy' });
	assert.equal(r.structuredContent.needs, 'confirm');
	assert.equal(mk4Op.state.state, 'Operational');
	r = await call(c, 'start_print', { printer: 'Prusa MK4', file: 'benchy', confirm: true });
	assert.equal(r.structuredContent.done, true, JSON.stringify(r));
	await waitFor(async () => (await stateOf(mk4.id)) === 'printing', 'printing');
	r = await call(c, 'list_printers');
	assert.equal(r.structuredContent.printers[0].state, 'printing');
	r = await call(c, 'cancel_print', { printer: 'Prusa MK4' });
	assert.equal(r.structuredContent.needs, 'confirm');
	r = await call(c, 'cancel_print', { printer: 'Prusa MK4', confirm: true });
	assert.equal(r.structuredContent.done, true);
	await waitFor(async () => (await stateOf(mk4.id)) === 'operational', 'cancelled');

	const audit = (await admin.get('/api/audit?action=job.')).data;
	assert.ok(audit.some((e) => e.action === 'job.start' && /via MCP token “Claude Code on the workshop Mac”/.test(e.detail)), 'start audited');
	assert.ok(audit.some((e) => e.action === 'job.cancel' && /via MCP token/.test(e.detail)), 'cancel audited');

	log('MCP over HTTP: bad token, cross-site origin, GET');
	let res = await fetch(`${APP}/mcp`, { method: 'POST', headers: { 'content-type': 'application/json', accept: 'application/json, text/event-stream', authorization: 'Bearer ocx_nope' }, body: '{}' });
	assert.equal(res.status, 401);
	res = await fetch(`${APP}/mcp`, { method: 'POST', headers: { 'content-type': 'application/json', accept: 'application/json, text/event-stream', authorization: `Bearer ${token}`, origin: 'http://evil.example' }, body: '{}' });
	assert.equal(res.status, 403);
	res = await fetch(`${APP}/mcp`, { headers: { authorization: `Bearer ${token}` } });
	assert.equal(res.status, 405);
	// A session cookie opens nothing on /mcp.
	const cookieRes = await fetch(`${APP}/mcp`, { method: 'POST', headers: { 'content-type': 'application/json', accept: 'application/json, text/event-stream' }, body: JSON.stringify({ jsonrpc: '2.0', id: 1, method: 'tools/list' }) });
	assert.equal(cookieRes.status, 401);

	log('a read-only token from the API: no control tools');
	const ro = (await admin.post('/api/integrations/tokens', { scope: 'mcp', name: 'Read only', access: 'read' })).data;
	const rc = await mcp(ro.token);
	const roTools = (await rc.listTools()).tools.map((t) => t.name);
	assert.ok(!roTools.includes('start_print') && roTools.includes('list_printers'));
	assert.equal((await call(rc, 'list_printers')).structuredContent.count, 2);

	for (const p of pages) assert.deepEqual(p.errors, [], 'no browser errors');
	log('all MCP e2e checks passed');
}

async function cleanup(ok) {
	for (const c of mcpClients) await c.close().catch(() => {});
	await browser?.close().catch(() => {});
	if (process.env.E2E_KEEP) {
		log(`E2E_KEEP: app still running on ${APP} (pid ${app?.pid}), data in ${dataDir}`);
		return;
	}
	app?.kill();
	for (const c of closers) await Promise.resolve(c()).catch(() => {});
	if (ok) rmSync(dataDir, { recursive: true, force: true });
}

try {
	await main();
	await cleanup(true);
	process.exit(0);
} catch (err) {
	console.error('✗ e2e failed:', err);
	console.error(`  app log: ${join(dataDir, 'app.log')}`);
	await cleanup(false);
	process.exit(1);
}
