// Synthetic, slicer-flavoured G-code for the toolpath viewer's tests, e2e run and
// performance numbers. No real models: a parametric "spool hub" (a ring with a hole,
// rectilinear infill, solid top/bottom, a skirt) emitted the way each slicer writes it.
//
//   node scripts/gcode-samples.mjs <out-dir>            # small samples (prusa, cura, orca, plain)
//   node scripts/gcode-samples.mjs <out-dir> --big 100  # plus big-<N>mb.gcode, about N MB
//
// Flavours:
//   prusa  PrusaSlicer: ;LAYER_CHANGE, ;Z:, ;TYPE:External perimeter…, M83 relative E
//   cura   Cura: ;LAYER:n, ;TYPE:WALL-OUTER / SKIN / FILL, M82 absolute E with G92 E0 per layer
//   orca   OrcaSlicer: ;LAYER_CHANGE, ;TYPE:Outer wall…, G2/G3 arcs for round walls, z-hop travels
//   plain  no comments at all (layers come from Z), G91 relative moves for the purge line
import { createWriteStream, mkdirSync, statSync } from 'node:fs';
import { once } from 'node:events';
import { join } from 'node:path';

const f3 = (v) => (Math.round(v * 1000) / 1000).toFixed(3);
const f5 = (v) => (Math.round(v * 100000) / 100000).toFixed(5);

const NAMES = {
	prusa: { outer: 'External perimeter', inner: 'Perimeter', sparse: 'Internal infill', solid: 'Solid infill', top: 'Top solid infill', skirt: 'Skirt/Brim' },
	orca: { outer: 'Outer wall', inner: 'Inner wall', sparse: 'Sparse infill', solid: 'Internal solid infill', top: 'Top surface', skirt: 'Skirt' },
	cura: { outer: 'WALL-OUTER', inner: 'WALL-INNER', sparse: 'FILL', solid: 'SKIN', top: 'SKIN', skirt: 'SKIRT' },
	plain: null
};

/**
 * Generates G-code line batches (strings) for a ring part.
 * opts: layers, layerHeight, outerR, innerR, segments (per circle), sparseSpacing, cx, cy
 */
export function* generate(flavour, opts = {}) {
	const o = { layers: 40, layerHeight: 0.2, outerR: 30, innerR: 10, segments: 120, sparseSpacing: 4, solidSpacing: 0.45, cx: 110, cy: 110, perimeters: 2, ...opts };
	const names = NAMES[flavour];
	const relE = flavour !== 'cura';
	const ePerMm = 0.033; // 0.45 mm line, 0.2 mm layer, 1.75 mm filament
	let E = 0;
	let x = 0;
	let y = 0;
	const out = [];
	const flush = () => {
		const s = out.join('\n') + '\n';
		out.length = 0;
		return s;
	};
	const extrude = (nx, ny) => {
		const d = Math.hypot(nx - x, ny - y);
		const de = d * ePerMm;
		E += de;
		out.push(`G1 X${f3(nx)} Y${f3(ny)} E${f5(relE ? de : E)}`);
		x = nx;
		y = ny;
	};
	const travel = (nx, ny, z, hop) => {
		if (relE) out.push('G1 E-0.8 F2100');
		else {
			E -= 0.8;
			out.push(`G1 F2100 E${f5(E)}`);
		}
		if (hop) out.push(`G1 Z${f3(z + 0.4)} F720`);
		out.push(`G0 F9000 X${f3(nx)} Y${f3(ny)}`);
		if (hop) out.push(`G1 Z${f3(z)} F720`);
		if (relE) out.push('G1 E0.8 F2100');
		else {
			E += 0.8;
			out.push(`G1 F2100 E${f5(E)}`);
		}
		x = nx;
		y = ny;
	};
	const type = (key) => {
		if (!names) return;
		out.push(`;TYPE:${names[key]}`);
		if (flavour === 'prusa' || flavour === 'orca') out.push(';WIDTH:0.45');
	};
	const circle = (r, z, key, useArcs) => {
		const sx = o.cx + r;
		const sy = o.cy;
		travel(sx, sy, z, flavour === 'orca');
		type(key);
		out.push('G1 F1800');
		if (useArcs) {
			// Two half circles, counter-clockwise.
			const half = Math.PI * r * ePerMm;
			E += half;
			out.push(`G3 X${f3(o.cx - r)} Y${f3(o.cy)} I${f3(-r)} J0 E${f5(relE ? half : E)}`);
			E += half;
			out.push(`G3 X${f3(sx)} Y${f3(sy)} I${f3(r)} J0 E${f5(relE ? half : E)}`);
			x = sx;
			y = sy;
			return;
		}
		for (let k = 1; k <= o.segments; k++) {
			const a = (k / o.segments) * Math.PI * 2;
			extrude(o.cx + r * Math.cos(a), o.cy + r * Math.sin(a));
		}
	};
	/** Rectilinear infill between the walls at angle ±45°. */
	const infill = (z, spacing, key, angle) => {
		const R = o.outerR - 0.45 * o.perimeters;
		const r = o.innerR + 0.45 * o.perimeters;
		const ca = Math.cos(angle);
		const sa = Math.sin(angle);
		const rot = (u, v) => [o.cx + u * ca - v * sa, o.cy + u * sa + v * ca];
		let first = true;
		let flip = false;
		for (let v = -R + spacing / 2; v < R; v += spacing) {
			const U = Math.sqrt(R * R - v * v);
			const spans = Math.abs(v) < r ? [[-U, -Math.sqrt(r * r - v * v)], [Math.sqrt(r * r - v * v), U]] : [[-U, U]];
			if (flip) spans.reverse();
			for (const [a0, a1] of spans) {
				const [u0, u1] = flip ? [a1, a0] : [a0, a1];
				const [px, py] = rot(u0, v);
				const [qx, qy] = rot(u1, v);
				if (first) {
					travel(px, py, z, flavour === 'orca');
					type(key);
					out.push('G1 F3000');
					first = false;
				} else if (Math.hypot(px - x, py - y) > spacing * 2.5) travel(px, py, z, false);
				else extrude(px, py);
				extrude(qx, qy);
			}
			flip = !flip;
		}
	};

	// Start G-code.
	if (flavour === 'prusa') out.push('; generated by PrusaSlicer 2.8.1 (synthetic sample)');
	if (flavour === 'orca') out.push('; generated by OrcaSlicer 2.2.0 (synthetic sample)');
	if (flavour === 'cura') out.push(';FLAVOR:Marlin', `;LAYER_COUNT:${o.layers}`, ';Generated with Cura_SteamEngine 5.8.0 (synthetic sample)');
	out.push('M140 S60', 'M104 S215', 'G28', 'G90', relE ? 'M83' : 'M82', 'M190 S60', 'M109 S215');
	// Purge line at the front edge.
	out.push('G1 Z0.3 F720', 'G1 X10 Y5 F9000');
	x = 10;
	y = 5;
	if (flavour === 'plain') {
		out.push('G91');
		out.push(`G1 X60 E${f5(60 * ePerMm * 1.5)} F1000`, `G1 X40 E${f5(40 * ePerMm * 1.5)}`);
		out.push('G90');
		x = 110;
	} else {
		if (!relE) out.push('G92 E0');
		extrude(70, 5);
		extrude(110, 5);
	}
	if (!relE) out.push('G92 E0'), (E = 0);
	yield flush();

	for (let l = 0; l < o.layers; l++) {
		const z = Math.round((0.2 + l * o.layerHeight) * 1000) / 1000;
		if (flavour === 'prusa' || flavour === 'orca') out.push(';LAYER_CHANGE', `;Z:${f3(z)}`, `;HEIGHT:${l ? o.layerHeight : 0.2}`);
		if (flavour === 'cura') {
			out.push(`;LAYER:${l}`);
			out.push('G92 E0');
			E = 0;
		}
		out.push(`G1 Z${f3(z)} F720`);
		if (flavour === 'prusa' && l % 10 === 0) out.push(`M73 P${Math.round((l / o.layers) * 100)} R${o.layers - l}`);
		if (l === 0) circle(o.outerR + 5, z, 'skirt', false);
		const arcs = flavour === 'orca';
		for (let p = o.perimeters - 1; p >= 0; p--) circle(o.outerR - 0.45 * p, z, p === 0 ? 'outer' : 'inner', arcs);
		for (let p = 0; p < o.perimeters; p++) circle(o.innerR + 0.45 * p, z, p === 0 ? 'outer' : 'inner', arcs);
		const solid = l < 3 || l >= o.layers - 3;
		infill(z, solid ? o.solidSpacing : o.sparseSpacing, solid ? (l >= o.layers - 1 ? 'top' : 'solid') : 'sparse', (l % 2 ? -1 : 1) * (Math.PI / 4));
		yield flush();
	}
	if (names) out.push(';TYPE:Custom');
	out.push('G1 E-2 F2100', `G1 Z${f3(0.2 + o.layers * o.layerHeight + 10)} F720`, 'G1 X0 Y200 F3000', 'M104 S0', 'M140 S0', 'M84');
	yield flush();
}

/** The whole file as a string (small samples). */
export function sample(flavour, opts) {
	return [...generate(flavour, opts)].join('');
}

/** Writes a sample to disk, streaming; returns its size. */
export async function writeSample(file, flavour, opts) {
	const out = createWriteStream(file);
	for (const chunk of generate(flavour, opts)) if (!out.write(chunk)) await once(out, 'drain');
	out.end();
	await once(out, 'finish');
	return statSync(file).size;
}

/** Options for a big Prusa-style file of roughly `mb` megabytes (dense: 0.1 mm layers, fine circles, 1 mm infill). */
export function bigOptions(mb) {
	// ~134 KB per layer with these settings.
	return { layers: Math.max(10, Math.round((mb * 1024 * 1024) / 134_000)), layerHeight: 0.1, segments: 720, sparseSpacing: 1.0, outerR: 45, innerR: 12, perimeters: 3 };
}

if (import.meta.url === `file://${process.argv[1]}`) {
	const dir = process.argv[2];
	if (!dir) {
		console.error('usage: node scripts/gcode-samples.mjs <out-dir> [--big MB]');
		process.exit(1);
	}
	mkdirSync(dir, { recursive: true });
	for (const f of ['prusa', 'cura', 'orca', 'plain']) {
		const size = await writeSample(join(dir, `ring-${f}.gcode`), f);
		console.log(`ring-${f}.gcode ${(size / 1024).toFixed(0)} KB`);
	}
	const bi = process.argv.indexOf('--big');
	if (bi > 0) {
		const mb = Number(process.argv[bi + 1] ?? 100);
		const size = await writeSample(join(dir, `big-${mb}mb.gcode`), 'prusa', bigOptions(mb));
		console.log(`big-${mb}mb.gcode ${(size / 1024 / 1024).toFixed(1)} MB`);
	}
}
